"""
Builds the web-ready scroll sequence used by components/site/Hero.tsx.

Input : a video file (e.g. NEW.mp4, needs ffmpeg on PATH) or a folder of frames (*.jpg / *.png)
Output: public/sequence/1280/NNN.webp and public/sequence/960/NNN.webp
        components/site/sequenceManifest.ts (maps each scroll frame to an image file)

Every source frame becomes a scroll frame, but an image is only stored when it has
visibly changed since the last stored one (THRESHOLD, mean pixel difference 0-255 on
a small greyscale copy). Slow or still parts therefore cost almost nothing, fast parts
keep every frame, and the hero crossfades between stored images so it stays smooth.

Usage (needs Python 3 and Pillow: pip install pillow):
    python scripts/optimize-sequence.py path/to/NEW.mp4
    python scripts/optimize-sequence.py path/to/frames/
"""

import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageChops, ImageStat

THRESHOLD = 0.8
SIZES = {1280: 72, 960: 70}  # width -> WebP quality

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "public" / "sequence"
MANIFEST = ROOT / "components" / "site" / "sequenceManifest.ts"


def source_frames(src: Path, tmp: Path) -> list[Path]:
    if src.is_dir():
        return sorted([*src.glob("*.jpg"), *src.glob("*.png")])
    subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(src), "-vsync", "0", str(tmp / "f_%05d.png")],
        check=True,
    )
    return sorted(tmp.glob("f_*.png"))


def thumb(path: Path) -> Image.Image:
    with Image.open(path) as im:
        return im.convert("L").resize((160, 90))


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])

    with tempfile.TemporaryDirectory() as tmp:
        sources = source_frames(src, Path(tmp))
        if not sources:
            sys.exit(f"No frames found in {src}")

        for width in SIZES:
            folder = OUT_DIR / str(width)
            folder.mkdir(parents=True, exist_ok=True)
            for old in folder.glob("*.webp"):
                old.unlink()

        frames: list[int] = []  # scroll frame -> stored image id
        last_thumb = None
        for path in sources:
            t = thumb(path)
            changed = last_thumb is None or ImageStat.Stat(ImageChops.difference(t, last_thumb)).mean[0] >= THRESHOLD
            if changed:
                image_id = len(set(frames))
                last_thumb = t
                with Image.open(path) as im:
                    im = im.convert("RGB")
                    for width, quality in SIZES.items():
                        height = round(im.height * width / im.width)
                        im.resize((width, height), Image.LANCZOS).save(
                            OUT_DIR / str(width) / f"{image_id:03d}.webp", "WEBP", quality=quality, method=6
                        )
                frames.append(image_id)
            else:
                frames.append(frames[-1])

    MANIFEST.write_text(
        "// Generated by scripts/optimize-sequence.py. Do not edit by hand.\n"
        "// Each entry is the image file (public/sequence/<width>/NNN.webp) shown for that scroll frame.\n"
        f"export const SEQUENCE_WIDTHS = [{', '.join(str(w) for w in sorted(SIZES))}] as const;\n"
        f"export const SEQUENCE_FRAMES: number[] = [{', '.join(map(str, frames))}];\n",
        encoding="utf-8",
    )
    print(f"{len(sources)} source frames -> {len(set(frames))} stored images")


if __name__ == "__main__":
    main()
