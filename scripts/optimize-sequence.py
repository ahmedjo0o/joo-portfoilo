"""
Builds the web-ready scroll sequence used by components/VisualScroll.tsx.

Input : a folder of full-size frames named person_00000.jpg, person_00001.jpg, ...
Output: public/sequence/1280/NNN.webp and public/sequence/960/NNN.webp
        components/site/sequenceManifest.ts (maps each scroll frame to an image file)

It keeps every STEP-th frame, stores identical (held) frames only once, and
re-encodes them as WebP at two widths (desktop and mobile).

Usage (needs Python 3 and Pillow: pip install pillow):
    python scripts/optimize-sequence.py path/to/original/frames
"""

import hashlib
import sys
from pathlib import Path

from PIL import Image

STEP = 2  # keep every 2nd frame
SIZES = {1280: 80, 960: 78}  # width -> WebP quality

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "public" / "sequence"
MANIFEST = ROOT / "components" / "site" / "sequenceManifest.ts"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src_dir = Path(sys.argv[1])
    sources = sorted(src_dir.glob("person_*.jpg"))
    if not sources:
        sys.exit(f"No person_*.jpg frames found in {src_dir}")

    for width in SIZES:
        (OUT_DIR / str(width)).mkdir(parents=True, exist_ok=True)

    frames: list[int] = []  # scroll frame -> unique image id
    ids: dict[str, int] = {}  # file hash -> unique image id
    for src in sources[::STEP]:
        digest = hashlib.md5(src.read_bytes()).hexdigest()
        if digest not in ids:
            image_id = len(ids)
            ids[digest] = image_id
            with Image.open(src) as im:
                im = im.convert("RGB")
                for width, quality in SIZES.items():
                    height = round(im.height * width / im.width)
                    im.resize((width, height), Image.LANCZOS).save(
                        OUT_DIR / str(width) / f"{image_id:03d}.webp",
                        "WEBP",
                        quality=quality,
                        method=6,
                    )
        frames.append(ids[digest])

    MANIFEST.write_text(
        "// Generated by scripts/optimize-sequence.py. Do not edit by hand.\n"
        "// Each entry is the image file (public/sequence/<width>/NNN.webp) shown for that scroll frame.\n"
        f"export const SEQUENCE_WIDTHS = [{', '.join(str(w) for w in sorted(SIZES))}] as const;\n"
        f"export const SEQUENCE_FRAMES: number[] = [{', '.join(map(str, frames))}];\n",
        encoding="utf-8",
    )
    print(f"{len(sources)} source frames -> {len(frames)} scroll frames, {len(ids)} unique images")


if __name__ == "__main__":
    main()
